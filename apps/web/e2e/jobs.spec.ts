import { test, expect, request as requests, type APIRequestContext } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createDatabase } from '@salesmora/data';
test.setTimeout(120000);
const connection = process.env.TEST_DATABASE_URL;
if (!connection || !new URL(connection).pathname.endsWith('_test') || connection === process.env.DATABASE_URL) throw Error('Use the isolated test database.');
const db = createDatabase(connection), origin = 'http://127.0.0.1:3002', headers = { Origin: origin }, prefix = `jobs-${randomUUID()}`;
const clients: Record<string, APIRequestContext> = {}, users: Record<string, string> = {};
let workspaceId: string, customerId: string, jobId: string;
const detail = (id = jobId) => `/api/jobs/${id}?workspace=${workspaceId}`;
test.beforeAll(async () => {
  await db('rateLimits').delete();
  for (const role of ['owner', 'admin', 'office', 'field', 'other']) {
    clients[role] = await requests.newContext({ baseURL: origin });
    const email = `${prefix}-${role}@example.test`;
    expect((await clients[role].post('/api/auth/sign-up/email', { headers, data: { name: `Jobs ${role}`, email, password: 'Fictional-test-password-42!', termsAccepted: true } })).status()).toBe(200);
    users[role] = (await db('users').where({ email }).first()).id;
  }
  const response = await clients.owner.post('/api/workspaces', { headers, data: { business: { businessName: 'Jobs Integration Fixture', businessType: 'plumbing' }, services: { services: ['repairs'], postalCode: '', serviceRange: '' }, team: { invitations: [] } } });
  expect(response.status()).toBe(201); workspaceId = (await response.json()).workspaceId;
  await db('workspaceMemberships').insert(['admin', 'office', 'field'].map(role => ({ workspaceId, userId: users[role], role })));
  const customer = await clients.owner.post('/api/customers', { headers, data: { workspaceId, submissionId: randomUUID(), values: { name: 'Jordan Jobs Fixture', type: 'person', companyName: '', email: '', phone: '', location: '', internalNotes: '', ownerId: '' } } });
  expect(customer.status()).toBe(201); customerId = (await customer.json()).customerId;
});
test.afterAll(async () => {
  if (Object.values(users).length) await db('users').whereIn('id', Object.values(users)).delete();
  await Promise.all(Object.values(clients).map(client => client.dispose())); await db.destroy();
});
async function change(action: string, extra: Record<string, unknown> = {}, role = 'owner', version?: number) {
  const record = await (await clients.owner.get(detail())).json();
  return clients[role].patch(`/api/jobs/${jobId}`, { headers, data: { workspaceId, jobId, submissionId: randomUUID(), expectedVersion: version ?? record.job.version, action, ...extra } });
}
test('Jobs APIs enforce role, tenant, lifecycle, current grants, retries and scoped aggregates', async () => {
  const { context: deadline } = await (await clients.owner.get(`/api/jobs/creation-deadline?workspace=${workspaceId}`)).json();
  const input = { completionDeadline: deadline.projectedDate, deadlineIntent: { mode: 'workspace', revision: deadline.revision }, deadlinePreview: { revision: deadline.revision, createdDate: deadline.createdDate, resolvedDate: deadline.projectedDate, timezone: deadline.timezone }, workspaceId, submissionId: randomUUID(), customerId, title: 'Repair leaking valve', primaryOwnerId: users.field, teamUserIds: [], service: 'Plumbing' };
  const created = await clients.owner.post('/api/jobs', { headers, data: input });
  expect(created.status()).toBe(201); jobId = (await created.json()).jobId;
  expect((await clients.owner.post('/api/jobs', { headers, data: input })).status()).toBe(201);
  expect((await clients.field.post('/api/jobs', { headers, data: { ...input, submissionId: randomUUID() } })).status()).toBe(404);
  expect((await clients.other.get(detail())).status()).toBe(404);
  expect((await clients.owner.patch(`/api/jobs/${jobId}`, { headers: { Origin: 'https://other.example' }, data: {} })).status()).toBe(403);
  expect((await change('deadline', { completionDeadline: '2026-02-30' })).status()).toBe(422);
  expect((await change('status', { to: 'scheduled' })).status()).toBe(422);
  expect((await change('schedule', { scheduledDate: '2026-10-23', arrivalWindow: '09:00-11:00' })).status()).toBe(200);
  expect((await change('deadline', { completionDeadline: '2020-01-01' })).status()).toBe(200);
  // Calendar defaults allow primary Field scheduling; explicitly revoke it to test current denial.
  await db('workspaceRolePolicies').where({ workspaceId, role: 'field', permission: 'jobs.schedule.update' }).delete();
  expect((await change('schedule', { scheduledDate: null, arrivalWindow: null }, 'field')).status()).toBe(404);
  let row = await (await clients.field.get(detail())).json();
  expect(row.job.capabilities.note).toBe(true); expect(row.job.capabilities.schedule).toBe(false);
  const stale = row.job.version;
  expect((await change('status', { to: 'waiting', waitingReason: 'materials' }, 'field')).status()).toBe(200);
  expect((await change('deadline', { completionDeadline: null }, 'owner', stale)).status()).toBe(409);
  const note = { workspaceId, jobId, submissionId: randomUUID(), expectedVersion: 1, action: 'note', body: 'Customer confirmed access.' };
  expect((await clients.field.patch(`/api/jobs/${jobId}`, { headers, data: note })).status()).toBe(200);
  expect((await clients.field.patch(`/api/jobs/${jobId}`, { headers, data: note })).status()).toBe(200);
  row = await (await clients.owner.get(detail())).json(); expect(row.activity.filter((e: { type: string }) => e.type === 'note')).toHaveLength(1);
  const list = await (await clients.field.get(`/api/jobs?workspace=${workspaceId}&service=Plumbing&deadline=overdue`)).json();
  expect(list.total).toBe(1); expect(list.metrics).toEqual({ active: 1, waiting: 1, overdue: 1, unassigned: 0 });
  expect(list.options.customers).toHaveLength(0); expect(list.rows[0].number).toBe('J-0001');
  expect((await clients.owner.get(`/api/jobs?workspace=${workspaceId}&sort=invalid`)).status()).toBe(422);
  expect((await change('assign', { primaryOwnerId: users.office, teamUserIds: [] })).status()).toBe(200);
  expect((await clients.field.get(detail())).status()).toBe(404);
  const after = await (await clients.field.get(`/api/jobs?workspace=${workspaceId}`)).json();
  expect(after.total).toBe(0); expect(after.metrics.active).toBe(0); expect(after.options.customerNames).toEqual([]);
  expect((await change('status', { to: 'completed' })).status()).toBe(422);
  expect((await change('status', { to: 'completed', confirmed: true }, 'office')).status()).toBe(200);
  expect((await change('note', { body: 'Closed note' })).status()).toBe(422);
  expect((await change('status', { to: 'in-progress', confirmed: true, reopenDeadline: null }, 'office')).status()).toBe(404);
  expect((await change('status', { to: 'in-progress', confirmed: true, reopenDeadline: null }, 'admin')).status()).toBe(200);
});
test('reviewed Jobs components create, persist, move, schedule and add notes on live pages', async ({ browser }) => {
  const context = await browser.newContext({ storageState: await clients.owner.storageState() });
  const page = await context.newPage(); page.setDefaultTimeout(15000);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${origin}/jobs?workspace=${workspaceId}`);
  await expect(page.getByRole('heading', { name: 'Jobs', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Jobs', exact: true })).toHaveAttribute('href', `/jobs?workspace=${workspaceId}`);
  await page.getByRole('button', { name: 'Create job', exact: true }).first().click();
  const createDialog = page.getByRole('dialog');
  await createDialog.getByRole('combobox', { name: 'Customer', exact: true }).selectOption(customerId);
  await expect(createDialog.getByRole('option', { name: 'Create a new customer' })).toHaveCount(0);
  await createDialog.getByLabel('Job title', { exact: true }).fill('UI persisted boiler repair');
  await createDialog.getByRole('combobox', { name: 'Primary owner', exact: true }).selectOption(users.field);
  await createDialog.getByRole('button', { name: 'Review job', exact: true }).click();
  await expect(createDialog.getByRole('heading', { name: 'Review new job' })).toBeVisible();
  const before = await db('jobs').where({ workspaceId, title: 'UI persisted boiler repair' }); expect(before).toHaveLength(0);
  await createDialog.getByRole('button', { name: 'Confirm and create' }).click();
  await expect(page).toHaveURL(/\/jobs\/[a-f\d-]+\?workspace=/);
  await expect(page.getByRole('heading', { name: 'UI persisted boiler repair', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Files', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Job team chat', exact: true })).toBeVisible();
  await page.getByLabel('Note for the job history').fill('Saved from the integrated component.');
  const noteSaved = page.waitForResponse(response => response.url().includes('/api/jobs/') && response.request().method() === 'PATCH');
  await page.getByRole('button', { name: 'Add note', exact: true }).click();
  expect((await noteSaved).status()).toBe(200);
  await expect(page.getByLabel('Note for the job history')).toHaveValue('');
  await expect(page.getByText('Saved from the integrated component.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Saved from the integrated component.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Schedule work', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Scheduled work date', { exact: true }).fill('2026-10-26');
  await page.getByRole('dialog').getByRole('button', { name: 'Save schedule', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('Scheduled', { exact:true })).toBeVisible();
  await page.getByRole('button', { name: 'Change status', exact: true }).click();
  await page.getByRole('dialog').getByRole('combobox', { name: 'New status' }).selectOption('waiting');
  await page.getByRole('dialog').getByRole('combobox', { name: 'Waiting reason' }).selectOption('customer');
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm change' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  const stored = await db('jobs').where({ workspaceId, title: 'UI persisted boiler repair' }).first();
  expect(stored.status).toBe('waiting'); expect(stored.waitingReason).toBe('customer');
  // Keep this denial check independent of policy changes made by other tests.
  await db('workspaceRolePolicies').where({ workspaceId, role: 'field', permission: 'jobs.schedule.update' }).delete();
  const fieldContext = await browser.newContext({ storageState: await clients.field.storageState() });
  const fieldPage = await fieldContext.newPage();
  await fieldPage.goto(`${origin}/jobs/${stored.id}?workspace=${workspaceId}`);
  await expect(fieldPage.getByRole('heading', { name: 'UI persisted boiler repair', exact: true })).toBeVisible();
  await expect(fieldPage.getByRole('button', { name: 'Schedule work', exact: true })).toHaveCount(0);
  await expect(fieldPage.getByLabel('Note for the job history')).toBeEditable();
  await page.screenshot({ path: '/tmp/jobs-live-detail.png', fullPage: true });
  await fieldPage.setViewportSize({ width: 375, height: 900 });
  await fieldPage.screenshot({ path: '/tmp/jobs-live-field.png', fullPage: true });
  expect(errors).toEqual([]);
  await fieldContext.close(); await context.close();
});
