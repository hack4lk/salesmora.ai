import { expect as baseExpect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createDatabase } from '@salesmora/data';
const expect = baseExpect.configure({ timeout: 40_000 });
const target = process.env.TEST_DATABASE_URL;
if (!target || !new URL(target).pathname.endsWith('_test') || target === process.env.DATABASE_URL) throw Error('Isolated test database required.');
const db = createDatabase(target), origin = process.env.SALESMORA_E2E_ORIGIN ?? 'http://127.0.0.1:3002';
test.afterAll(async () => db.destroy());
test('real wizard creates once after a lost acknowledgement, saves, reloads and rejects a stale tab', async ({ context, page }) => {
  test.setTimeout(360_000);
  context.setDefaultTimeout(40_000);
  const headers = { Origin: origin };
  expect((await context.request.post('/api/auth/sign-up/email', { headers, data: { name: 'Capture Owner', email: `capture-${randomUUID()}@example.test`, password: 'Fictional-capture-password-42!', termsAccepted: true, plan: 'free' } })).ok()).toBe(true);
  const created = await context.request.post('/api/workspaces', { headers, data: { business: { businessName: 'Capture Test Business', businessType: 'plumbing' }, services: { services: ['drain-cleaning'], postalCode: '10013', serviceRange: '25-miles' }, team: { invitations: [] } } });
  expect(created.status()).toBe(201); const { workspaceId } = await created.json();
  // Connected lead settings: real initialization, lost save acknowledgement and two-tab conflict.
  const initialSettings = await context.request.get(`/api/settings/leads?workspace=${workspaceId}`);
  expect(initialSettings.status()).toBe(200); expect(initialSettings.headers()['cache-control']).toContain('no-store'); expect(initialSettings.headers()['vary']).toContain('Cookie');
  expect((await initialSettings.json()).value).toEqual({ kind: 'unassigned' });
  const ownerId = (await db('workspaces').where({ id: workspaceId }).first('ownerId')).ownerId;
  await page.goto(`/settings?workspace=${workspaceId}`);
  await page.getByRole('region', { name: 'Leads', exact: true }).getByRole('link', { name: 'Lead settings', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Leads', exact: true })).toBeVisible();
  await page.getByRole('radio', { name: 'Assign to one selected teammate', exact: true }).check();
  await page.getByRole('combobox', { name: /^Teammate/ }).selectOption(ownerId);
  let lostSetting = false;
  await page.route('**/api/settings/leads**', async route => {
    if (route.request().method() !== 'PUT' || lostSetting) return route.continue();
    lostSetting = true; await route.fetch(); await route.abort('failed');
  });
  await page.getByRole('button', { name: 'Save default assignment', exact: true }).click();
  await expect(page.getByText('The setting could not be saved. Your changes are still here.', { exact: true })).toBeVisible();
  await expect(page.getByRole('combobox', { name: /^Teammate/ })).toHaveValue(ownerId);
  await page.getByRole('button', { name: 'Save default assignment', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save default assignment', exact: true })).toBeDisabled();
  expect((await db('leadAssignmentSettingsAudit').where({ workspaceId })).length).toBe(1);
  await page.unroute('**/api/settings/leads**');
  const staleSettings = await context.newPage(); await staleSettings.goto(`/settings/leads?workspace=${workspaceId}`);
  await expect(staleSettings.getByRole('combobox')).toHaveValue(ownerId);
  await page.getByRole('radio', { name: 'Leave leads unassigned for manual assignment', exact: true }).check();
  await page.getByRole('button', { name: 'Save default assignment', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save default assignment', exact: true })).toBeDisabled();
  await staleSettings.getByRole('radio', { name: 'Leave leads unassigned for manual assignment', exact: true }).check();
  await staleSettings.getByRole('button', { name: 'Save default assignment', exact: true }).click();
  await expect(staleSettings.getByText('This setting changed. Reload the saved rule before making another change.', { exact: true })).toBeVisible();
  await expect(staleSettings.getByRole('radio', { name: 'Leave leads unassigned for manual assignment', exact: true })).toBeChecked();
  await staleSettings.getByRole('button', { name: 'Reload setting', exact: true }).click();
  await expect(staleSettings.getByRole('alertdialog')).toBeVisible();
  await staleSettings.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(staleSettings.getByRole('radio', { name: 'Leave leads unassigned for manual assignment', exact: true })).toBeChecked();
  await staleSettings.getByRole('button', { name: 'Reload setting', exact: true }).click();
  await staleSettings.getByRole('alertdialog').getByRole('button', { name: 'Reload saved rule', exact: true }).click();
  await expect(staleSettings.getByRole('button', { name: 'Save default assignment', exact: true })).toBeDisabled();
  await staleSettings.close();
  expect((await db('leadAssignmentSettingsAudit').where({ workspaceId })).length).toBe(2);
  const currentSetting = await (await context.request.get(`/api/settings/leads?workspace=${workspaceId}`)).json();
  expect(currentSetting.version).toBe(3); expect(currentSetting.value).toEqual({ kind: 'unassigned' });
  expect((await context.request.put('/api/settings/leads', { headers: { Origin: 'https://other.example.test' }, data: { workspaceId, requestId: randomUUID(), expectedVersion: 3, value: { kind: 'unassigned' } } })).status()).toBe(403);
  expect((await context.request.put('/api/settings/leads', { headers, data: { workspaceId, requestId: randomUUID(), expectedVersion: 3, value: { kind: 'unassigned' }, actorId: 'forged' } })).status()).toBe(422);
  expect((await context.request.get(`/api/settings/leads?workspace=${randomUUID()}`)).status()).toBe(404);
  await page.reload(); await expect(page.getByRole('radio', { name: 'Leave leads unassigned for manual assignment', exact: true })).toBeChecked();
  await page.goto(`/lead-capture?workspace=${workspaceId}`);
  await expect(page.getByRole('heading', { name: 'Lead Capture', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create capture source' }).click();
  await page.getByRole('textbox', { name: 'Capture source name', exact: true }).fill('Website requests');
  let lost = false;
  await page.route('**/api/lead-capture', async route => {
    if (route.request().method() !== 'POST' || lost) return route.continue();
    lost = true; await route.fetch(); await route.abort('failed');
  });
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Try again', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page).toHaveURL(/\/lead-capture\/[0-9a-f-]+\/setup\?.*step=intake/);
  expect((await db('captureSources').where({ workspaceId })).length).toBe(1);
  const source = await db('captureSources').where({ workspaceId }).first();
  await expect(page.getByRole('button', { name: /Suggest fields/ })).toBeDisabled();
  // Resolve labels through the approved component's accessible text.
  const textarea = page.locator('textarea').first(); await textarea.fill('Capture plumbing requests and contact information.');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save draft', exact: true })).toBeDisabled();
  await page.reload(); await expect(page.locator('textarea').first()).toHaveValue('Capture plumbing requests and contact information.');
  const stale = await context.newPage(); await stale.goto(page.url());
  await page.locator('textarea').first().fill('Saved by first tab'); await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save draft', exact: true })).toBeDisabled();
  await stale.locator('textarea').first().fill('Corrections in second tab'); await stale.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(stale.getByRole('button', { name: 'Reload saved draft', exact: true })).toBeVisible();
  await expect(stale.locator('textarea').first()).toHaveValue('Corrections in second tab');
  expect((await db('captureSourceDrafts').where({ sourceId: source.id }).first()).configuration.brief).toBe('Saved by first tab');
  await stale.getByRole('button', { name: 'Reload saved draft', exact: true }).click();
  await stale.getByRole('alertdialog').getByRole('button', { name: 'Reload saved draft', exact: true }).click();
  await expect(stale.locator('textarea').first()).toHaveValue('Saved by first tab'); await stale.close();
  expect((await db('capturePublications').where({ workspaceId })).length).toBe(0); expect((await db('leads').where({ workspaceId })).length).toBe(0);
  const response = await context.request.get(`/api/lead-capture/${source.id}?workspace=${workspaceId}`); expect(response.status()).toBe(200); expect(response.headers()['cache-control']).toContain('no-store');
  expect((await context.request.put(`/api/lead-capture/${source.id}/draft`, { headers: { Origin: 'https://foreign.example' }, data: {} })).status()).toBe(403);
  expect((await context.request.get(`/api/lead-capture/${source.id}?workspace=${randomUUID()}`)).status()).toBe(404);
  await page.screenshot({ path: '/private/tmp/capture-live-wizard.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 800 }); await page.reload();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/lead-capture/${source.id}?workspace=${workspaceId}`);
  await page.getByRole('tab', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Edit setup', exact: true }).click();
  await expect(page.locator('textarea').first()).toBeVisible();
  await page.locator('textarea').first().fill('Unsaved navigation corrections');
  await page.getByRole('link', { name: 'Home', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toBeVisible();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(page.locator('textarea').first()).toHaveValue('Unsaved navigation corrections');
  await page.evaluate(() => history.back());
  await expect(page.getByRole('alertdialog')).toBeVisible();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(page.locator('textarea').first()).toHaveValue('Unsaved navigation corrections');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save draft', exact: true })).toBeDisabled();
  const publicationReviewResponse = await context.request.get(`/api/lead-capture/${source.id}/publication?workspace=${workspaceId}`);
  expect(publicationReviewResponse.status()).toBe(200); const publicationReview = await publicationReviewResponse.json();
  expect(publicationReview.ready).toBe(false); expect(publicationReview.checks).toContainEqual({ code:'delivery', ready:false });
  const deniedPublication = await context.request.post(`/api/lead-capture/${source.id}/publication`, { headers, data: { workspaceId, sourceId: source.id, expectedVersion: publicationReview.sourceVersion, draftVersion: publicationReview.draftVersion, configurationVersion: publicationReview.configurationVersion, baseApprovedVersion: publicationReview.baseApprovedVersion, confirmed:true, requestId:randomUUID(), timing:{kind:'now'} } });
  expect(deniedPublication.status()).toBe(422); expect((await deniedPublication.json()).failures).toContain('delivery');
  expect((await db('captureSourceVersions').where({workspaceId})).length).toBe(0);
  await page.goto(`/lead-capture/${source.id}/setup?workspace=${workspaceId}&step=review`);
  await expect(page.getByText('Form or Gmail delivery is not enabled for this workspace.', {exact:true})).toBeVisible();
  await expect(page.getByText('0 of 1 published-source slots used', {exact:true})).toBeVisible();
  await db('workspaces').where({ id: workspaceId }).update({ planOverride: 'standard', planOverrideEndsAt: new Date(Date.now() + 86_400_000), planOverrideReason: 'Browser fixture', planOverrideId: randomUUID() });
  const gmail = await context.request.post('/api/lead-capture', { headers, data: { workspaceId, requestId: randomUUID(), name: 'Gmail requests', configuration: { schemaVersion: 1, type: 'gmail' } } });
  expect(gmail.status()).toBe(200); const gmailSource = await gmail.json();
  await page.goto(`/lead-capture/${gmailSource.sourceId}/setup?workspace=${workspaceId}&step=intake&panel=fields`);
  await expect(page.getByText('Email sample mapping is not available yet. Your draft settings can be saved for later.', { exact: true })).toBeVisible();
  await expect(page.locator('textarea')).toHaveCount(0);
  await page.getByRole('tab', { name: 'Email account', exact: true }).click();
  await expect(page.getByRole('button', { name: /Connect Gmail/ })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled();

});
